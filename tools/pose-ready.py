"""Author and inspect the stationary ready pose in Blender before exporting its targets."""
from json import dumps
from pathlib import Path
import sys

import bpy
from mathutils import Matrix, Quaternion, Vector

output = Path(sys.argv[sys.argv.index('--') + 1])
output.mkdir(parents=True, exist_ok=True)
scene = bpy.context.scene
rig = next(obj for obj in scene.objects if obj.type == 'ARMATURE')
bones = {bone.name.split(':')[-1].removeprefix('mixamorig'): bone for bone in rig.pose.bones}

def world(name):
    return rig.matrix_world @ bones[name].matrix

def set_world(name, matrix):
    bones[name].matrix = rig.matrix_world.inverted() @ matrix
    bpy.context.view_layer.update()

def aim(name, child, target):
    matrix = world(name)
    origin, rotation, scale = matrix.decompose()
    direction = world(child).translation - origin
    delta = direction.rotation_difference(target - origin)
    set_world(name, Matrix.LocRotScale(origin, delta @ rotation, scale))

def points(name, middle, end, target, pole):
    origin = world(name).translation
    center = world(middle).translation
    a, b = (center - origin).length, (world(end).translation - center).length
    ray = target - origin
    distance = min(a + b - .002, ray.length)
    ray.normalize()
    along = (a*a - b*b + distance*distance) / (2 * distance)
    bend = (pole - ray * pole.dot(ray)).normalized()
    joint = origin + ray * along + bend * (a*a - along*along)**.5
    aim(name, middle, joint)
    aim(middle, end, target)

hip_position, hip_rotation, hip_scale = world('Hips').decompose()
drop = .143
set_world('Hips', Matrix.LocRotScale(hip_position + Vector((0, 0, -drop)), hip_rotation, hip_scale))
lean = .17
for name in ['Spine1', 'Neck']:
    center, rotation, scale = world(name).decompose()
    pitch = lean if name == 'Spine1' else -lean * .72
    set_world(name, Matrix.LocRotScale(center, Quaternion((1, 0, 0), pitch) @ rotation, scale))
for side, sign in [('Right', -1), ('Left', 1)]:
    foot_rotation = world(side + 'Foot').to_quaternion()
    ankle = Vector((sign*.15, -.025, .087))
    points(side + 'UpLeg', side + 'Leg', side + 'Foot', ankle, Vector((sign*.12, -1, 0)))
    center, _, scale = world(side + 'Foot').decompose()
    set_world(side + 'Foot', Matrix.LocRotScale(center, foot_rotation, scale))
    target = Vector((sign * (.21 if side == 'Right' else .205), -.365, 1.055 if side == 'Right' else 1.035))
    points(side + 'Arm', side + 'ForeArm', side + 'Hand', target, Vector((sign*.32, .25, -1)))

shaft = Vector((.10, -.80, .59)).normalized()
def hand_frame(axis, direction, up):
    x = direction.normalized() * axis
    z = x.cross(up).normalized()
    return Matrix((x, z.cross(x), z)).transposed().to_quaternion()

wrists = {}
for side, sign in [('Right', -1), ('Left', 1)]:
    hand = side + 'Hand'
    center, _, scale = world(hand).decompose()
    wrists[side] = center.copy()
    direction = shaft if side == 'Right' else center - world(side + 'ForeArm').translation
    set_world(hand, Matrix.LocRotScale(center, hand_frame(sign, direction, Vector((0, 0, 1))), scale))
    for finger in ['Index', 'Middle', 'Ring', 'Pinky']:
        for digit, curl in enumerate((.64, .88, .62) if side == 'Right' else (.18, .26, .20), 1):
            bone = bones[hand + finger + str(digit)]
            bone.rotation_mode = 'QUATERNION'
            bone.rotation_quaternion = Quaternion((0, 0, 1), -sign * curl)

# Coordinates in the game's metres, with +Z facing the net.
to_game = lambda v: [round(v.x, 4), round(v.z, 4), round(-v.y, 4)]
samples = dict(hipDrop=drop, chestLean=lean, racketHand=to_game(wrists['Right']), freeHand=to_game(wrists['Left']), shaft=to_game(shaft))
(output / 'ready-pose.js').write_text('// Generated by tools/pose-ready.py from the Blender ready pose.\nexport const readyPose = ' + dumps(samples, indent=2) + ';\n')

# Lightweight racket silhouette and studio lighting for checking balance from behind.
grip = wrists['Right']
mat = bpy.data.materials.new('Review racket')
mat.diffuse_color = (.09, .25, .31, 1)
bpy.ops.mesh.primitive_cylinder_add(vertices=20, radius=.013, depth=.45, location=grip + shaft * .225)
handle = bpy.context.object
handle.rotation_euler = shaft.to_track_quat('Z', 'Y').to_euler()
handle.data.materials.append(mat)
bpy.ops.mesh.primitive_torus_add(major_radius=.105, minor_radius=.007, location=grip + shaft*.535)
hoop = bpy.context.object
hoop.rotation_euler = shaft.cross(Vector((1, 0, 0))).to_track_quat('Z', 'Y').to_euler()
hoop.data.materials.append(mat)
bpy.ops.mesh.primitive_plane_add(size=200)
bpy.context.object.location.z = -.01
floor = bpy.data.materials.new('Court blue')
floor.diffuse_color = (.035, .13, .16, 1)
bpy.context.object.data.materials.append(floor)
bpy.ops.object.camera_add(location=(2.7, 5.2, 2.55))
camera = bpy.context.object
camera.rotation_euler = (Vector((0, 0, .97)) - camera.location).to_track_quat('-Z', 'Y').to_euler()
camera.data.type = 'ORTHO'
camera.data.ortho_scale = 2.35
scene.camera = camera
scene.render.engine = 'BLENDER_WORKBENCH'
scene.display.shading.light = 'STUDIO'
scene.display.shading.color_type = 'MATERIAL'
scene.display.shading.show_shadows = True
scene.display.shading.show_cavity = True
scene.render.resolution_x = scene.render.resolution_y = 600
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = 'PNG'
scene.render.filepath = str(output / 'lingchuan-ready.png')
bpy.context.preferences.filepaths.save_version = 0
bpy.ops.wm.save_as_mainfile(filepath=str(output / 'lingchuan-ready.blend'))
bpy.ops.render.render(write_still=True)
