import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { AnimationMixer, LoopOnce, Vector3 } from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

const [source, output] = process.argv.slice(2);
if (!source || !output) throw new Error('请用 npm run motion:sync 运行带验证的导入流程。');
const bytes = await readFile(resolve(source, 'dist/models/athlete-animations.glb'));
const checksum = createHash('sha256').update(bytes).digest('hex');
const asset = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
const root = asset.scene;
const bonesByName = new Map();
root.traverse(node => {
  if (node.isBone) bonesByName.set(node.name.replace('mixamorig', '').replace(/[^a-zA-Z0-9]/g, ''), node);
});
function bone(name) {
  const value = bonesByName.get(name);
  if (!value) throw new Error(`GLB 缺少骨骼 ${name}`);
  return value;
}
function marker(name) {
  const value = root.getObjectByName(name);
  if (!value) throw new Error(`GLB 缺少标记 ${name}`);
  return value;
}
const contact = marker('RacketContact');
const grip = marker('RacketGrip');
const face = marker('RacketFaceNormal');
const mixer = new AnimationMixer(root);
const point = name => bone(name).getWorldPosition(new Vector3());
const headings = new Vector3();
const gripBones = ['RightHandThumb1', 'RightHandIndex2', 'RightHandMiddle2', 'RightHandRing2', 'RightHandPinky2'];
const round = x => Math.round(x * 10000) / 10000;
const actions = {};
const bones = ['Hips', 'LeftFoot', 'RightFoot', 'LeftHand', 'RightForeArm'];
for (const direction of ['straight', 'cross']) {
  const name = `backhand_${direction}`;
  const clip = asset.animations.find(item => item.name === name);
  if (!clip || !Number.isFinite(clip.duration) || clip.duration <= 0) throw new Error(`GLB 缺少有效动作 ${name}`);
  mixer.stopAllAction();
  const action = mixer.clipAction(clip).reset().setLoop(LoopOnce, 1).play();
  action.paused = true;
  function at(progress) {
    action.time = progress * clip.duration;
    mixer.update(0);
    root.updateMatrixWorld(true);
  }
  at(0);
  const gripRest = gripBones.map(name => bone(name).quaternion.clone());
  actions[direction] = Array.from({ length: 121 }, (_, frame) => {
    at(frame / 120);
    const center = contact.getWorldPosition(new Vector3());
    const shaft = center.clone().sub(grip.getWorldPosition(new Vector3())).normalize();
    const normal = face.getWorldPosition(new Vector3()).sub(center).normalize();
    const shoulder = headings.copy(point('RightArm')).sub(point('LeftArm'));
    const footHeading = side => {
      const toe = point(side + 'ToeBase').sub(point(side + 'Foot'));
      return Math.atan2(-toe.x, -toe.z);
    };
    const curl = gripBones.map((name, i) => gripRest[i].angleTo(bone(name).quaternion));
    return [...bones.flatMap(name => point(name).toArray()), ...center.toArray(), ...shaft.toArray(), ...normal.toArray(),
      Math.atan2(-shoulder.z, shoulder.x), footHeading('Left'), footHeading('Right'), ...curl].map(round);
  });
}
for (const [name, frames] of Object.entries(actions)) {
  if (frames.some(row => row.length !== 32 || !row.every(Number.isFinite))) throw new Error(`${name} 包含无效采样`);
  const hit = frames[60];
  if (Math.hypot(...hit.slice(18, 21)) < .9 || Math.hypot(...hit.slice(21, 24)) < .9) {
    throw new Error(`${name} 的球拍标记无法定义拍面`);
  }
}
const entries = Object.entries(actions).map(([name, frames]) =>
  `  ${name}: [\n${frames.map(frame => `    ${JSON.stringify(frame)}`).join(',\n')}\n  ]`);
await writeFile(output,
  `// Source GLB sha256: ${checksum}\n// Generated by tools/build-backhand-motion.mjs from the Court Lab GLB.\nexport const backhandClips = {\n${entries.join(',\n')}\n};\n`);
